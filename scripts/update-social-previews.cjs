// Run with Node.js and sharp available (NODE_PATH may point to the bundled runtime).
// Generated metadata must stay in HTML: messaging crawlers do not run page scripts.
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const sharp = require('sharp');
const root = path.resolve(__dirname, '..');
const origin = 'https://movieyourenglish.vercel.app';
const width = 1200, height = 630;
const escape = value => String(value).replaceAll('&', '&amp;').replaceAll('"', '&quot;').replaceAll('<', '&lt;').replaceAll('>', '&gt;');
const decode = value => value.replaceAll('&amp;', '&').replaceAll('&quot;', '"').replaceAll('&#39;', "'");
const sandbox = { window: {} };
vm.runInNewContext(fs.readFileSync(path.join(root, 'learning-data.js'), 'utf8'), sandbox);
const lessons = sandbox.window.MYE_LEARNING_CATALOG.lessons;
const publicPages = ['index.html', 'movies.html', 'how-it-works.html', 'social-proof.html', 'my-learning.html'];
const files = [
  ...lessons.map(lesson => ({ file: lesson.href, image: lesson.poster, imageKey: lesson.movieSlug, alt: `${lesson.title} movie poster`, title: `${lesson.title} — ${lesson.level} English lesson | Movie Your English`, description: `Practice English with ${lesson.title}. ${lesson.level} activities before, during, and after the movie: vocabulary, comprehension, and your own response.` })),
  ...publicPages.map(file => ({ file, image: 'assets/mye-logo.png', imageKey: 'movie-your-english', alt: 'Movie Your English logo', brand: true }))
];

(async () => {
  const outputDir = path.join(root, 'assets', 'social-previews');
  fs.mkdirSync(outputDir, { recursive: true });
  const generated = new Set();
  for (const page of files) {
    const preview = `${page.imageKey}.jpg`;
    if (!generated.has(preview)) {
      await sharp(path.join(root, page.image)).rotate()
        .resize(width, height, { fit: page.brand ? 'contain' : 'cover', position: 'centre', background: '#061715' })
        .flatten({ background: '#061715' }).jpeg({ quality: 85, mozjpeg: true })
        .toFile(path.join(outputDir, preview));
      generated.add(preview);
    }
    const htmlPath = path.join(root, page.file);
    let html = fs.readFileSync(htmlPath, 'utf8');
    const title = page.title || decode(html.match(/<title>([\s\S]*?)<\/title>/i)?.[1] || 'Movie Your English');
    const description = page.description || decode(html.match(/<meta\s+name="description"\s+content="([^"]*)"/i)?.[1] || 'Learn English with the movies you love.');
    const url = `${origin}/${page.file === 'index.html' ? '' : page.file}`;
    const image = `${origin}/assets/social-previews/${preview}`;
    const tags = [
      '<!-- Social preview: generated by scripts/update-social-previews.cjs -->',
      `<meta property="og:type" content="website">`,
      `<meta property="og:site_name" content="Movie Your English">`,
      `<meta property="og:locale" content="en_US">`,
      `<meta property="og:title" content="${escape(title)}">`,
      `<meta property="og:description" content="${escape(description)}">`,
      `<meta property="og:url" content="${escape(url)}">`,
      `<meta property="og:image" content="${image}">`,
      `<meta property="og:image:secure_url" content="${image}">`,
      `<meta property="og:image:type" content="image/jpeg">`,
      `<meta property="og:image:width" content="${width}">`,
      `<meta property="og:image:height" content="${height}">`,
      `<meta property="og:image:alt" content="${escape(page.alt)}">`,
      `<meta name="twitter:card" content="summary_large_image">`,
      `<meta name="twitter:title" content="${escape(title)}">`,
      `<meta name="twitter:description" content="${escape(description)}">`,
      `<meta name="twitter:image" content="${image}">`,
      `<meta name="twitter:image:alt" content="${escape(page.alt)}">`,
      '<!-- /Social preview -->'
    ].map(line => `  ${line}`).join('\n');
    // Only replace our generated block; leave all hand-authored page content alone.
    html = html.replace(/[ \t]*<!-- Social preview: generated by scripts\/update-social-previews.cjs -->[\s\S]*?<!-- \/Social preview -->\r?\n?/g, '');
    html = html.replace(/[ \t]*<\/head>/i, `${tags}\n</head>`);
    fs.writeFileSync(htmlPath, html);
  }
  console.log(`Updated ${files.length} HTML pages and ${generated.size} social-preview JPEGs.`);
})().catch(error => { console.error(error); process.exitCode = 1; });
